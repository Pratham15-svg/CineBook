const pool = require("../config/db");

// 1. View shows scheduled at the manager's venue
const getVenueShows = async (req, res) => {
    try {
        const managerId = req.user.userId;

        const result = await pool.query(
            `SELECT
                s.show_id,
                m.title AS movie_title,
                v.name AS venue_name,
                sc.screen_name,
                s.start_time,
                s.end_time,
                COUNT(DISTINCT se.seat_no) AS total_seats,
                COUNT(DISTINCT bs.seat_no) FILTER (
                    WHERE b.status = 'CONFIRMED'
                ) AS booked_seats
             FROM venue v
             JOIN screen sc ON sc.venue_id = v.venue_id
             JOIN movie_show s ON s.screen_id = sc.screen_id
             JOIN movie m ON m.movie_id = s.movie_id
             LEFT JOIN seat se ON se.screen_id = sc.screen_id
             LEFT JOIN booking_seat bs
                ON bs.show_id = s.show_id
                AND bs.screen_id = sc.screen_id
                AND bs.seat_no = se.seat_no
                AND bs.is_active = TRUE
             LEFT JOIN booking b ON b.booking_id = bs.booking_id
             WHERE v.manager_id = $1
             GROUP BY
                s.show_id, m.title, v.name,
                sc.screen_name, s.start_time, s.end_time
             ORDER BY s.start_time`,
            [managerId]
        );

        res.json({
            success: true,
            count: result.rows.length,
            shows: result.rows
        });

    } catch (error) {
        console.error("Get venue shows error:", error.message);
        res.status(500).json({
            success: false,
            message: "Unable to retrieve venue shows"
        });
    }
};

// 2. View occupancy of shows at the manager's venue
const getVenueOccupancy = async (req, res) => {
    try {
        const managerId = req.user.userId;

        const result = await pool.query(
            `SELECT
                s.show_id,
                m.title AS movie_title,
                v.name AS venue_name,
                sc.screen_name,
                s.start_time,
                COUNT(DISTINCT se.seat_no) AS total_seats,
                COUNT(DISTINCT bs.seat_no) FILTER (
                    WHERE b.status = 'CONFIRMED'
                ) AS booked_seats,
                ROUND(
                    100.0 * COUNT(DISTINCT bs.seat_no) FILTER (
                        WHERE b.status = 'CONFIRMED'
                    ) / NULLIF(COUNT(DISTINCT se.seat_no), 0),
                    2
                ) AS occupancy_percentage
             FROM venue v
             JOIN screen sc ON sc.venue_id = v.venue_id
             JOIN movie_show s ON s.screen_id = sc.screen_id
             JOIN movie m ON m.movie_id = s.movie_id
             LEFT JOIN seat se ON se.screen_id = sc.screen_id
             LEFT JOIN booking_seat bs
                ON bs.show_id = s.show_id
                AND bs.screen_id = sc.screen_id
                AND bs.seat_no = se.seat_no
                AND bs.is_active = TRUE
             LEFT JOIN booking b ON b.booking_id = bs.booking_id
             WHERE v.manager_id = $1
             GROUP BY
                s.show_id, m.title, v.name,
                sc.screen_name, s.start_time
             ORDER BY s.start_time`,
            [managerId]
        );

        res.json({
            success: true,
            occupancy: result.rows
        });

    } catch (error) {
        console.error("Venue occupancy error:", error.message);
        res.status(500).json({
            success: false,
            message: "Unable to retrieve occupancy"
        });
    }
};

// 3. View revenue generated by the manager's venue
const getVenueRevenue = async (req, res) => {
    try {
        const managerId = req.user.userId;

        const result = await pool.query(
            `SELECT
                v.venue_id,
                v.name AS venue_name,
                COALESCE(SUM(p.amount), 0) AS total_revenue
             FROM venue v
             LEFT JOIN screen sc ON sc.venue_id = v.venue_id
             LEFT JOIN movie_show s ON s.screen_id = sc.screen_id
             LEFT JOIN booking b
                ON b.show_id = s.show_id
                AND b.status = 'CONFIRMED'
             LEFT JOIN payment p
                ON p.booking_id = b.booking_id
                AND p.status = 'SUCCESS'
             WHERE v.manager_id = $1
             GROUP BY v.venue_id, v.name
             ORDER BY total_revenue DESC`,
            [managerId]
        );

        res.json({
            success: true,
            revenue: result.rows
        });

    } catch (error) {
        console.error("Venue revenue error:", error.message);
        res.status(500).json({
            success: false,
            message: "Unable to retrieve venue revenue"
        });
    }
};

